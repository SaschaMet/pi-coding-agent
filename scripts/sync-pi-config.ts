import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import process from "node:process";
import { pathToFileURL } from "node:url";
import { isDeepStrictEqual } from "node:util";

export type Mode = "pull" | "push";
type SyncOptions = { dryRun?: boolean };
type JsonObject = Record<string, unknown>;

const EXCLUDED_TOP_LEVEL_PATHS = new Set([
	"auth.json",
	"sessions",
	"npm",
	"models.json",
	"trust.json",
	"AGENTS.md",
	// Project MCP server approval store — per-machine runtime state, never mirrored.
	"mcp-project-approvals.json",
	// Global runtime caches — regenerated by the global PI runtime.
	// Never mirrored; a push must not delete them.
	"mcp-cache.json",
	"models-store.json",
	"pi-cache-optimizer-stats.d",
	// claude-bridge provider state — written by the global runtime, never mirrored.
	"claude-bridge.json",
	"claude-bridge-diag.log",
	"claude-bridge",
	// pi-mcp-adapter upgrade-notice marker — runtime state, a push must not delete it.
	"mcp-last-seen-version.json",
	// Per-machine UI preferences — never mirrored, a push must not delete them.
	"zentui.json",
	"themes",
	// pi-compact-tools release-notice markers — runtime state, a push must not delete them.
	"compact-tools-notices",
	// Sandboxed bash: live per-session settings files and the user's policy override.
	// A push that deletes them kills bash in every running sandboxed session.
	"sandbox-run",
	"sandbox.json",
]);
// Extension directories containing this marker file are considered
// system-managed and will be pruned from local during sync.
// User-created directories without the marker are left intact.
// See scripts/sync-pi-config.md for details.
const MANAGED_EXTENSION_MARKER = ".pi-managed";
const SETTINGS_RELATIVE_PATH = "settings.json";
// Per-machine pi state: never copied between project and global.
const MACHINE_LOCAL_SETTINGS_KEYS = ["lastChangelogVersion"];
const MCP_RELATIVE_PATH = "mcp.json";
const EXTENSIONS_RELATIVE_PATH = "extensions";

function resolveGlobalAgentDir(): string {
	const fromEnv = process.env.PI_CODING_AGENT_DIR?.trim();
	if (fromEnv) return path.resolve(fromEnv);
	return path.join(os.homedir(), ".pi", "agent");
}

function resolveClaudeConfigDir(): string {
	return path.join(os.homedir(), ".claude");
}

const SYSTEM_MD_RELATIVE_PATH = ".pi/SYSTEM.md";
const CLAUDE_MD_FILENAME = "CLAUDE.md";

export function copySystemMdToClaudeMd(
	projectRoot: string,
	{ dryRun = false }: SyncOptions = {},
): boolean {
	const sourcePath = path.join(projectRoot, SYSTEM_MD_RELATIVE_PATH);
	if (!fs.existsSync(sourcePath)) return false;

	const claudeDir = resolveClaudeConfigDir();
	const targetPath = path.join(claudeDir, CLAUDE_MD_FILENAME);

	const sourceBuf = fs.readFileSync(sourcePath);

	let wouldCopy = true;
	if (fs.existsSync(targetPath)) {
		const targetBuf = fs.readFileSync(targetPath);
		wouldCopy = !sourceBuf.equals(targetBuf);
	}
	if (!wouldCopy) return false;
	if (dryRun) return true;

	ensureDir(claudeDir);
	fs.writeFileSync(targetPath, sourceBuf);
	return true;
}

function parseArgs(
	argv: string[],
): { mode: Mode; dryRun: boolean; allowDelete: boolean } {
	const usage =
		"Usage: tsx scripts/sync-pi-config.ts <pull|push> [--dry-run] [--allow-delete]";
	const mode = argv[2] as Mode | undefined;
	if (!mode || (mode !== "pull" && mode !== "push")) {
		throw new Error(usage);
	}
	const extra = argv.slice(3);
	for (const arg of extra) {
		if (arg !== "--dry-run" && arg !== "--allow-delete") {
			throw new Error(usage);
		}
	}
	// The delete check only guards global files, which only a push can delete.
	if (extra.includes("--allow-delete") && mode !== "push") {
		throw new Error(usage);
	}
	return {
		mode,
		dryRun: extra.includes("--dry-run"),
		allowDelete: extra.includes("--allow-delete"),
	};
}

function ensureDir(dirPath: string): void {
	fs.mkdirSync(dirPath, { recursive: true });
}

// Extension files that stay in this repo until their rollout is decided.
// Sync never copies or deletes them; smoke skips them while no global copy exists.
// Remove an entry to roll the file out globally with the next push.
export const PROJECT_ONLY_EXTENSION_FILES: ReadonlySet<string> = new Set([
	"sandbox-bash.ts",
	"lib/sandbox-bash.ts",
]);

export function isProjectOnlyExtensionPath(extensionRelativePath: string): boolean {
	return PROJECT_ONLY_EXTENSION_FILES.has(extensionRelativePath.split(path.sep).join("/"));
}

function holdsProjectOnlyFile(localExtensionDir: string, extensionName: string): boolean {
	return [...PROJECT_ONLY_EXTENSION_FILES].some(
		(file) =>
			file.startsWith(`${extensionName}/`) &&
			fs.existsSync(path.join(localExtensionDir, file.slice(extensionName.length + 1))),
	);
}

export function isManagedRelativePath(relativePath: string): boolean {
	const normalized = relativePath.split(path.sep).join("/");
	if (!normalized) return false;
	if (path.posix.basename(normalized) === ".DS_Store") return false;

	const topLevel = normalized.split("/")[0];
	if (
		topLevel === EXTENSIONS_RELATIVE_PATH &&
		isProjectOnlyExtensionPath(normalized.slice(EXTENSIONS_RELATIVE_PATH.length + 1))
	) {
		return false;
	}
	return !EXCLUDED_TOP_LEVEL_PATHS.has(topLevel);
}

function listRelativeFilesRecursive(root: string): string[] {
	if (!fs.existsSync(root)) return [];
	const files: string[] = [];

	const walk = (relativeDir: string) => {
		const absoluteDir = relativeDir ? path.join(root, relativeDir) : root;

		for (const entry of fs.readdirSync(absoluteDir, { withFileTypes: true })) {
			const relativePath = relativeDir
				? path.posix.join(relativeDir.split(path.sep).join("/"), entry.name)
				: entry.name;

			if (!isManagedRelativePath(relativePath)) continue;

			if (entry.isDirectory()) {
				walk(relativePath);
				continue;
			}

			if (entry.isFile()) {
				files.push(relativePath);
			}
		}
	};

	walk("");
	return files.sort();
}

function getExtensionDirectoryName(relativePath: string): string | undefined {
	const normalized = relativePath.split(path.sep).join("/");
	const parts = normalized.split("/");
	if (parts.length < 3 || parts[0] !== EXTENSIONS_RELATIVE_PATH)
		return undefined;
	return parts[1];
}

function isExtensionsRelativePath(relativePath: string): boolean {
	const normalized = relativePath.split(path.sep).join("/");
	return (
		normalized === EXTENSIONS_RELATIVE_PATH ||
		normalized.startsWith(`${EXTENSIONS_RELATIVE_PATH}/`)
	);
}

function listExtensionDirectoryNames(root: string): Set<string> {
	const extensionsRoot = path.join(root, EXTENSIONS_RELATIVE_PATH);
	if (!fs.existsSync(extensionsRoot)) return new Set();

	return new Set(
		fs
			.readdirSync(extensionsRoot, { withFileTypes: true })
			.filter((entry) => entry.isDirectory())
			.map((entry) => entry.name),
	);
}

function removePulledGlobalExtensionDirectories(
	files: string[],
	globalAgentDir: string,
): string[] {
	const globalExtensionDirectories = listExtensionDirectoryNames(globalAgentDir);
	if (globalExtensionDirectories.size === 0) return files;

	return files.filter((relativePath) => {
		const extensionDirectory = getExtensionDirectoryName(relativePath);
		return (
			extensionDirectory === undefined ||
			!globalExtensionDirectories.has(extensionDirectory)
		);
	});
}

function parseObjectJson(text: string): JsonObject | undefined {
	try {
		const parsed = JSON.parse(text);
		if (!parsed || typeof parsed !== "object" || Array.isArray(parsed))
			return undefined;
		return parsed as JsonObject;
	} catch {
		return undefined;
	}
}

function parseNpmPackageName(spec: string): string | undefined {
	if (!spec.startsWith("npm:")) return undefined;

	const raw = spec.slice(4);
	if (!raw) return undefined;

	const atIndex = raw.lastIndexOf("@");
	if (atIndex <= 0) return raw;
	return raw.slice(0, atIndex);
}

function mergePackages(
	sourcePackages: string[],
	targetPackages: string[],
): string[] {
	const merged: string[] = [];
	const addExact = (value: string) => {
		if (!merged.includes(value)) merged.push(value);
	};

	for (const sourceValue of sourcePackages) addExact(sourceValue);

	for (const targetValue of targetPackages) {
		const targetName = parseNpmPackageName(targetValue);
		if (!targetName) {
			addExact(targetValue);
			continue;
		}

		const existingByNameIndex = merged.findIndex(
			(candidate) => parseNpmPackageName(candidate) === targetName,
		);
		if (existingByNameIndex === -1) {
			addExact(targetValue);
			continue;
		}

		merged[existingByNameIndex] = targetValue;
	}

	return merged;
}

function mergeSettingsPackages(
	sourceBuf: Buffer,
	targetBuf: Buffer,
): Buffer | undefined {
	const sourceJson = parseObjectJson(sourceBuf.toString("utf-8"));
	const targetJson = parseObjectJson(targetBuf.toString("utf-8"));
	if (!sourceJson || !targetJson) return undefined;

	const sourcePackages = Array.isArray(sourceJson.packages)
		? sourceJson.packages.filter((v): v is string => typeof v === "string")
		: [];
	const targetPackages = Array.isArray(targetJson.packages)
		? targetJson.packages.filter((v): v is string => typeof v === "string")
		: [];

	const merged: JsonObject = { ...targetJson, ...sourceJson };
	merged.packages = mergePackages(sourcePackages, targetPackages);
	for (const key of MACHINE_LOCAL_SETTINGS_KEYS) {
		if (key in targetJson) merged[key] = targetJson[key];
		else delete merged[key];
	}
	return Buffer.from(`${JSON.stringify(merged, null, 2)}\n`, "utf-8");
}

function getJsonObjectProperty(
	json: JsonObject,
	property: string,
): JsonObject | undefined {
	const value = json[property];
	if (!value || typeof value !== "object" || Array.isArray(value))
		return undefined;
	return value as JsonObject;
}

function mergeMcpServers(
	sourceBuf: Buffer,
	targetBuf: Buffer,
): Buffer | undefined {
	const sourceJson = parseObjectJson(sourceBuf.toString("utf-8"));
	const targetJson = parseObjectJson(targetBuf.toString("utf-8"));
	if (!sourceJson || !targetJson) return undefined;

	const sourceServers = getJsonObjectProperty(sourceJson, "mcpServers");
	const targetServers = getJsonObjectProperty(targetJson, "mcpServers");
	if (!sourceServers || !targetServers) return undefined;

	sourceJson.mcpServers = { ...sourceServers, ...targetServers };
	return Buffer.from(`${JSON.stringify(sourceJson, null, 2)}\n`, "utf-8");
}

function sameJson(a: Buffer, b: Buffer): boolean {
	const left = parseObjectJson(a.toString("utf-8"));
	const right = parseObjectJson(b.toString("utf-8"));
	return left !== undefined && right !== undefined && isDeepStrictEqual(left, right);
}

function fileMode(filePath: string): number {
	return fs.statSync(filePath).mode & 0o777;
}

// keepMode: a synced git hook without its exec bit is skipped by git silently.
function copyFileIfChanged(
	source: string,
	target: string,
	relativePath: string,
	keepMode: boolean,
	dryRun: boolean,
): boolean {
	const sourceBuf = fs.readFileSync(source);
	let outputBuf: Buffer<ArrayBufferLike> = sourceBuf;

	if (fs.existsSync(target)) {
		const targetBuf = fs.readFileSync(target);
		let merged: Buffer | undefined;
		if (relativePath === SETTINGS_RELATIVE_PATH) {
			merged = mergeSettingsPackages(sourceBuf, targetBuf);
		}
		if (relativePath === MCP_RELATIVE_PATH) {
			merged = mergeMcpServers(sourceBuf, targetBuf);
		}
		if (merged) outputBuf = merged;
		const sameMode = !keepMode || fileMode(source) === fileMode(target);
		// A merge reformats JSON; equal content in a different layout is not a change.
		if (merged && sameMode && sameJson(merged, targetBuf)) return false;
		if (outputBuf.equals(targetBuf) && sameMode) return false;
	}

	if (dryRun) return true;

	ensureDir(path.dirname(target));
	fs.writeFileSync(target, outputBuf);
	if (keepMode) fs.chmodSync(target, fileMode(source));
	return true;
}

function removeFileIfExists(filePath: string, dryRun: boolean): boolean {
	if (!fs.existsSync(filePath)) return false;
	if (dryRun) return true;
	fs.rmSync(filePath);
	return true;
}

function removeDirectoryIfExists(dirPath: string, dryRun: boolean): boolean {
	if (!fs.existsSync(dirPath)) return false;
	if (dryRun) return true;
	fs.rmSync(dirPath, { recursive: true, force: true });
	return true;
}

function isPreservedTargetOnlyRelativePath(
	mode: Mode,
	relativePath: string,
): boolean {
	if (mode === "pull" && isExtensionsRelativePath(relativePath)) return true;
	if (mode === "push" && getExtensionDirectoryName(relativePath) !== undefined)
		return true;
	return relativePath === MCP_RELATIVE_PATH;
}

function isManagedExtensionDir(dirPath: string): boolean {
	return fs.existsSync(path.join(dirPath, MANAGED_EXTENSION_MARKER));
}

function pruneLocalExtensionDirectoriesThatExistGlobally(
	localPiDir: string,
	globalAgentDir: string,
	dryRun: boolean,
): string[] {
	const globalExtensionDirectories = listExtensionDirectoryNames(globalAgentDir);
	if (globalExtensionDirectories.size === 0) return [];

	const removed: string[] = [];
	for (const extensionName of globalExtensionDirectories) {
		const globalExtPath = path.join(
			globalAgentDir,
			EXTENSIONS_RELATIVE_PATH,
			extensionName,
		);
		if (!isManagedExtensionDir(globalExtPath)) continue;

		const localExtensionDir = path.join(
			localPiDir,
			EXTENSIONS_RELATIVE_PATH,
			extensionName,
		);
		// Sync never widens what it deletes: a project-only file outlives any global twin folder.
		if (holdsProjectOnlyFile(localExtensionDir, extensionName)) continue;
		const relativeDir = `${EXTENSIONS_RELATIVE_PATH}/${extensionName}`;
		if (removeDirectoryIfExists(localExtensionDir, dryRun)) removed.push(relativeDir);
	}

	if (!dryRun) pruneEmptyManagedDirectories(localPiDir);
	return removed;
}

function pruneEmptyManagedDirectories(root: string, relativeDir = ""): void {
	const absoluteDir = relativeDir ? path.join(root, relativeDir) : root;
	if (!fs.existsSync(absoluteDir)) return;

	for (const entry of fs.readdirSync(absoluteDir, { withFileTypes: true })) {
		if (!entry.isDirectory()) continue;

		const childRelative = relativeDir
			? path.posix.join(relativeDir.split(path.sep).join("/"), entry.name)
			: entry.name;

		if (!isManagedRelativePath(childRelative)) continue;
		pruneEmptyManagedDirectories(root, childRelative);
	}

	if (!relativeDir) return;

	if (fs.readdirSync(absoluteDir).length === 0) {
		fs.rmdirSync(absoluteDir);
	}
}

export function syncManagedPiDirectory(
	mode: Mode,
	localPiDir: string,
	globalAgentDir: string,
	{ dryRun = false }: SyncOptions = {},
): {
	updated: string[];
	deleted: string[];
	directoriesRemoved: string[];
} {
	const sourceRoot = mode === "push" ? localPiDir : globalAgentDir;
	const targetRoot = mode === "push" ? globalAgentDir : localPiDir;
	if (!dryRun) ensureDir(targetRoot);
	const directoriesRemoved = pruneLocalExtensionDirectoriesThatExistGlobally(
		localPiDir,
		globalAgentDir,
		dryRun,
	);

	// A real run deletes these local folders before listing, so a dry run drops their files too.
	const prunedPrefixes = directoriesRemoved.map((dir) => `${dir}/`);
	const underPruned = (relativePath: string) =>
		prunedPrefixes.some((prefix) => relativePath.startsWith(prefix));

	const listedSourceFiles =
		mode === "pull"
			? removePulledGlobalExtensionDirectories(
					listRelativeFilesRecursive(sourceRoot),
					globalAgentDir,
				)
			: listRelativeFilesRecursive(sourceRoot);
	const sourceFiles = listedSourceFiles.filter((file) => !underPruned(file));
	const sourceSet = new Set(sourceFiles);

	const updated: string[] = [];
	for (const relativePath of sourceFiles) {
		const sourcePath = path.join(sourceRoot, relativePath);
		const targetPath = path.join(targetRoot, relativePath);
		if (
			copyFileIfChanged(sourcePath, targetPath, relativePath, mode === "push", dryRun)
		) {
			updated.push(relativePath);
		}
	}

	const deleted: string[] = [];
	for (const targetRelativePath of listRelativeFilesRecursive(targetRoot)) {
		if (sourceSet.has(targetRelativePath)) continue;
		if (underPruned(targetRelativePath)) continue;
		if (isPreservedTargetOnlyRelativePath(mode, targetRelativePath)) continue;
		const targetPath = path.join(targetRoot, targetRelativePath);
		if (removeFileIfExists(targetPath, dryRun)) deleted.push(targetRelativePath);
	}

	if (!dryRun) pruneEmptyManagedDirectories(targetRoot);

	return { updated, deleted, directoriesRemoved };
}

/**
 * PI, Claude, and every git commit fail closed on a policy that does not load,
 * so push refuses to ship one and the last good global copy stays in place.
 */
export async function checkSecurityPolicy(localPiDir: string): Promise<void> {
	const securityDir = path.join(localPiDir, "security");
	if (!fs.existsSync(securityDir)) return;
	try {
		const [core, policyModule] = await Promise.all([
			import(pathToFileURL(path.join(securityDir, "guard-core.ts")).href),
			import(pathToFileURL(path.join(securityDir, "policy.ts")).href),
		]);
		core.checkPolicy(policyModule.policy);
	} catch (error) {
		const message = error instanceof Error ? error.message : String(error);
		throw new Error(`Security policy check failed, nothing synced: ${message}`);
	}
}

export async function main(): Promise<void> {
	const { mode, dryRun, allowDelete } = parseArgs(process.argv);
	const projectRoot = process.cwd();
	const localPiDir = path.join(projectRoot, ".pi");
	const globalAgentDir = resolveGlobalAgentDir();

	if (!fs.existsSync(localPiDir)) {
		throw new Error(`Local .pi directory not found: ${localPiDir}`);
	}
	if (mode === "push") await checkSecurityPolicy(localPiDir);

	// Fail-closed: a push that would delete global files stops until it is rerun with --allow-delete.
	if (mode === "push" && !dryRun && !allowDelete) {
		const preview = syncManagedPiDirectory(mode, localPiDir, globalAgentDir, {
			dryRun: true,
		});
		if (preview.deleted.length > 0) {
			console.log(`\nPush would delete ${preview.deleted.length} global file(s):`);
			for (const file of preview.deleted) console.log(`  - ${file}`);
			throw new Error(
				"push would delete global files; rerun with --allow-delete, or preview with --dry-run",
			);
		}
	}

	if (!dryRun) ensureDir(globalAgentDir);

	console.log(
		`Sync start: mode=${mode}${dryRun ? " dryRun" : ""} local=${localPiDir} global=${globalAgentDir}`,
	);
	if (dryRun) console.log("DRY RUN: nothing written");
	const result = syncManagedPiDirectory(mode, localPiDir, globalAgentDir, { dryRun });

	console.log(`Mode: ${mode}`);
	console.log(`Local: ${localPiDir}`);
	console.log(`Global: ${globalAgentDir}`);

	if (result.directoriesRemoved.length > 0) {
		console.log(
			`\n${dryRun ? "Would remove" : "Directories removed"} (${result.directoriesRemoved.length}):`,
		);
		for (const dir of result.directoriesRemoved) {
			console.log(`  - ${dir}`);
		}
	}

	if (result.updated.length > 0) {
		console.log(`\n${dryRun ? "Would update" : "Updated"} files (${result.updated.length}):`);
		for (const file of result.updated) {
			console.log(`  - ${file}`);
		}
	}

	if (result.deleted.length > 0) {
		console.log(`\n${dryRun ? "Would delete" : "Deleted"} files (${result.deleted.length}):`);
		for (const file of result.deleted) {
			console.log(`  - ${file}`);
		}
	}

	if (
		result.directoriesRemoved.length === 0 &&
		result.updated.length === 0 &&
		result.deleted.length === 0
	) {
		console.log("No changes.");
	}

	if (copySystemMdToClaudeMd(projectRoot, { dryRun })) {
		console.log(
			`${dryRun ? "Would copy" : "Copied"} SYSTEM.md -> ${resolveClaudeConfigDir()}/${CLAUDE_MD_FILENAME}`,
		);
	} else {
		console.log("SYSTEM.md -> CLAUDE.md: no changes.");
	}
}

if (
	process.argv[1] &&
	import.meta.url === pathToFileURL(process.argv[1]).href
) {
	main().catch((error: unknown) => {
		console.error(error instanceof Error ? error.message : error);
		process.exitCode = 1;
	});
}
